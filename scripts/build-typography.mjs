#!/usr/bin/env node
/**
 * Typography catalog → CSS utility classes + semantic aliases.
 * Source: tokens/typography-catalog.json
 * Output: src/styles/typography.css
 */
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const catalog = JSON.parse(readFileSync(join(root, 'tokens/typography-catalog.json'), 'utf8'));
const outPath = join(root, 'src/styles/typography.css');

function slugToParts(slug) {
  const [group, ...rest] = slug.split('-');
  return { group, name: rest.join('-') };
}

function sizeVarForSlug(slug) {
  const { group, name } = slugToParts(slug);
  if (group === 'body' && name === 'lg') return '--font-size-body-lg';
  if (group === 'body' && name.startsWith('md')) return '--font-size-body-md';
  if (group === 'body' && name.startsWith('sm')) return '--font-size-body-sm';
  if (group === 'subtitle' && name.startsWith('xlg')) return '--font-size-subtitle-xlg';
  if (group === 'subtitle' && name.startsWith('md')) return '--font-size-subtitle-md';
  if (group === 'subtitle' && name.startsWith('sm')) return '--font-size-subtitle-sm';
  if (group === 'label') {
    const base = name.replace(/-bold$/, '');
    return `--font-size-label-${base}`;
  }
  if (group === 'heading') return `--font-size-heading-${name}`;
  return null;
}

function lineVarForStyle(style) {
  const { group, name } = slugToParts(style.slug);
  if (group === 'body' && name === 'lg') return '--line-height-subtitle-lg';
  if (group === 'body' && name.startsWith('md')) return '--line-height-body-md';
  if (group === 'body' && name.startsWith('sm')) return '--line-height-body-sm';
  if (group === 'subtitle' && name.startsWith('xlg')) return '--line-height-subtitle-xlg';
  if (group === 'subtitle' && name.startsWith('md')) return '--line-height-subtitle-md';
  if (group === 'subtitle' && name.startsWith('sm')) return '--line-height-subtitle-sm';
  if (group === 'label') {
    const base = name.replace(/-bold$/, '');
    return `--line-height-label-${base}`;
  }
  if (group === 'heading') return `--line-height-heading-${name}`;
  return null;
}

const allStyles = catalog.groups.flatMap((g) => g.styles);

const semanticLines = allStyles
  .map((style) => {
    const sizeVar = sizeVarForSlug(style.slug);
    const lineVar = lineVarForStyle(style);
    if (!sizeVar || !lineVar) return null;
    const prefix = `--text-${style.slug}`;
    const tracking = style.trackingVar ? `\n  ${prefix}-tracking: var(${style.trackingVar});` : '';
    return `  ${prefix}-size: var(${sizeVar});
  ${prefix}-line: var(${lineVar});${tracking}`;
  })
  .filter(Boolean);

const classLines = allStyles.map((style) => {
  const prefix = `--text-${style.slug}`;
  const weight = style.weight === 'bold' ? 'var(--font-weight-bold)' : 'var(--font-weight-regular)';
  const tracking = style.trackingVar ? `  letter-spacing: var(${style.trackingVar});\n` : '';
  const mono = style.mono
    ? '  font-variant-numeric: tabular-nums;\n'
    : '';
  return `.text-${style.slug} {
  font-family: var(--font-family-sans);
  font-size: var(${prefix}-size);
  line-height: var(${prefix}-line);
  font-weight: ${weight};
${tracking}${mono}}`;
});

// Text color utilities
const textColorUtilities = [
  ['primary', '--text-main-on-surface'],
  ['secondary', '--text-secondary-on-surface'],
  ['disabled', '--text-disabled-on-surface'],
  ['inverse', '--text-main-on-inverse-bg'],
]
  .map(
    ([name, varName]) => `.text-color-${name} {
  color: var(${varName});
}`,
  )
  .join('\n\n');

const css = `/* Generated by scripts/build-typography.mjs — do not edit by hand */
/* Rebuild: npm run typography:build */

/* Semantic typography aliases */
:root {
${semanticLines.join('\n')}
}

${classLines.join('\n\n')}

${textColorUtilities}
`;

writeFileSync(outPath, css, 'utf8');
console.log(`typography built: ${allStyles.length} styles → ${outPath}`);
