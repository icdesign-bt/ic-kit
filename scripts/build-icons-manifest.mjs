#!/usr/bin/env node
/**
 * Генерирует src/icons/manifest.ts из src/icons/svg (recursive)
 */
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'fs';
import { join, dirname, relative } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const svgRoot = join(root, 'src/icons/svg');
const outPath = join(root, 'src/icons/manifest.ts');
const catalogPath = join(root, 'tokens/icon-catalog.json');

function walkSvgFiles(dir, base = dir) {
  if (!existsSync(dir)) return [];
  const entries = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) entries.push(...walkSvgFiles(full, base));
    else if (name.endsWith('.svg')) entries.push(relative(base, full));
  }
  return entries;
}

const catalog = JSON.parse(
  readFileSync(catalogPath, 'utf8'),
);
const files = walkSvgFiles(svgRoot).sort();
const paths = catalog.icons.map((i) => i.path);

const header = `/* Generated by scripts/build-icons-manifest.mjs — do not edit */
import type { IconWeight } from './types';

export const ICON_PATHS = ${JSON.stringify(paths)} as const;

export type IconPath = (typeof ICON_PATHS)[number];

export const iconSvgModules = import.meta.glob('./svg/**/*.svg', {
  query: '?raw',
  import: 'default',
  eager: true,
}) as Record<string, string>;

export function resolveIconModule(path: string, weight: IconWeight): string | undefined {
  const [category, ...rest] = path.split('/');
  const name = rest.join('/');
  const slug = (s: string) =>
    s
      .replace(/&/g, 'and')
      .replace(/[^a-zA-Z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .toLowerCase();
  const key = \`./svg/\${slug(category)}/\${slug(name)}/\${weight}.svg\`;
  return iconSvgModules[key];
}

export const exportedIconCount = ${files.length};
`;

writeFileSync(outPath, header, 'utf8');
console.log(`manifest: ${files.length} svg files, ${paths.length} catalog paths → ${outPath}`);
